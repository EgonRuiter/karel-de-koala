def lang_of(src):
    """Return 'en' or 'nl' from a save dict or KarelApp instance."""
    d = getattr(src, "d", src) if src is not None else {}
    return "en" if isinstance(d, dict) and d.get("language") == "en" else "nl"


def tr(lang, nl_text):
    """Translate a static NL UI label to EN when lang == 'en'."""
    if lang == "en":
        return EN_UI.get(nl_text, nl_text)
    return nl_text


def trf(lang, key, **kw):
    """Format a localized message key in 'nl' or 'en'."""
    bank = _MSGS["en" if lang == "en" else "nl"]
    return bank[key].format(**kw)


def coin_u(lang):
    """Compact coin unit ('c' in English, 'm' in Dutch)."""
    return "c" if lang == "en" else "m"


def tr_cooldown(lang, key, nl_reason):
    if lang == "en":
        return EN_COOLDOWNS.get(key, nl_reason)
    return nl_reason


def tr_title(lang, nl_title):
    return EN_TITLES.get(nl_title, nl_title) if lang == "en" else nl_title


def tr_event(lang, title, buff):
    if lang == "en" and title in EN_EVENTS:
        return EN_EVENTS[title]
    return title, buff


def tr_item(lang, item_id, nl_name, nl_desc=""):
    if lang == "en" and item_id in EN_ITEMS:
        en_n, en_d = EN_ITEMS[item_id]
        return en_n, (en_d or nl_desc)
    return nl_name, nl_desc


def tr_perk(lang, wid, nl_desc):
    return EN_PERKS.get(wid, nl_desc) if lang == "en" else nl_desc


def tr_committee(lang, cid, nl_name, nl_desc, nl_quote=""):
    if lang == "en" and cid in EN_COMMITTEES:
        return EN_COMMITTEES[cid]
    return nl_name, nl_desc, nl_quote


def tr_ach(lang, canonical_name, nl_desc):
    if lang == "en" and canonical_name in EN_ACHIEVEMENTS:
        return EN_ACHIEVEMENTS[canonical_name]
    return canonical_name, nl_desc


def tr_quest(lang, qid, nl_label, tgt):
    if lang == "en" and qid in EN_QUESTS:
        return EN_QUESTS[qid](tgt)
    return nl_label


def tr_arcade_row(lang, key, nl_title, nl_desc):
    if lang == "en" and key in EN_ARCADE:
        return EN_ARCADE[key]
    return nl_title, nl_desc


def tr_trivia_pick(lang, idx, q_txt, opts, ans_idx):
    if lang == "en" and 0 <= idx < len(EN_TRIVIA):
        return EN_TRIVIA[idx]
    return q_txt, opts, ans_idx


def pick_quote(lang, category, nl_pool):
    if lang == "en" and category in EN_QUOTES:
        return random.choice(EN_QUOTES[category])
    return random.choice(nl_pool)
